function main() {
  const write = process.argv.includes('--write');
  const raw = fs.readFileSync(SCENARIO_FILE, 'utf8');
  const scenario = JSON.parse(raw);
  if (JSON.stringify(scenario) + '\n' !== raw) throw new Error('剧本不是标准 JSON.stringify 输出，拒绝改写');

  const factionName = (key) => (key === 'player' ? '明廷' : ((scenario.factions || []).find((f) => f.id === key) || {}).name);
  const seen = new Set();
  let changed = 0;
  Object.entries(scenario.adminHierarchy).forEach(([key, tree]) => {
    (tree.divisions || []).forEach((division) => {
      const id = factionName(key) + '/' + division.name;
      if (!Object.prototype.hasOwnProperty.call(DESCRIPTIONS, id)) return;
      seen.add(id);
      if (division.description !== DESCRIPTIONS[id]) {
        division.description = DESCRIPTIONS[id];
        changed += 1;
      }
    });
  });
  const missing = Object.keys(DESCRIPTIONS).filter((id) => !seen.has(id));
  if (missing.length) throw new Error('剧本里找不到这些省：' + missing.join('、'));

  console.log('省级描述：' + seen.size + ' 省，改写 ' + changed + ' 处');
  if (write) {
    fs.writeFileSync(SCENARIO_FILE, JSON.stringify(scenario) + '\n');
    console.log('已写入 ' + path.relative(REPO, SCENARIO_FILE));
  } else {
    console.log('（试算，未写入；加 --write 写入）');
  }
}

main();
