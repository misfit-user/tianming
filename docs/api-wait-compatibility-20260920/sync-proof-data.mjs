import fs from 'node:fs';
import cp from 'node:child_process';
import path from 'node:path';
import crypto from 'node:crypto';
const dir = 'docs/api-wait-compatibility-20260920';
const hash = b => crypto.createHash('sha256').update(b).digest('hex');
const base = JSON.parse(fs.readFileSync(dir + '/baseline.json', 'utf8'));
const changes = JSON.parse(fs.readFileSync(dir + '/changes.json', 'utf8'));
const file = 'web/startup-script-phases.json', before = fs.readFileSync(file);
const prior = changes.filter(r => r.file === file).at(-1);
if (prior && hash(before) !== prior.after) throw Error('Generated manifest changed concurrently');
const backup = path.join(base.backup, file);
fs.mkdirSync(path.dirname(backup), { recursive: true });
if (!fs.existsSync(backup)) fs.writeFileSync(backup, before, { flag: 'wx' });
const indexHash = hash(fs.readFileSync('web/index.html'));
cp.execFileSync(process.execPath, ['web/scripts/build-startup-phase-manifest.js'], { stdio: 'inherit' });
if (hash(fs.readFileSync('web/index.html')) !== indexHash) throw Error('Index changed during generation');
changes.push({ file, before: hash(before), after: hash(fs.readFileSync(file)), at: new Date().toISOString(), generator: 'web/scripts/build-startup-phase-manifest.js' });
fs.writeFileSync(dir + '/changes.json', JSON.stringify(changes, null, 2));
cp.execFileSync(process.execPath, ['web/scripts/build-startup-phase-manifest.js', '--check'], { stdio: 'inherit' });
const original = 'docs/endturn-final-closeout-20260919/check-diff.mjs';
const target = dir + '/check-diff.mjs';
if (!fs.existsSync(target)) fs.writeFileSync(target, fs.readFileSync(original, 'utf8').replaceAll('docs/endturn-final-closeout-20260919', dir));
