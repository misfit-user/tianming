import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
const root=path.resolve(process.argv[2]||'.');
const work=fs.realpathSync(path.join(root,'docs/shaosong-map-integration-20260917'));
const stage=path.join(work,'map-stage'),tag=process.argv[3]||'installed-ui-third';
if(!/^installed-ui-[a-z0-9-]+$/.test(tag))throw Error('Invalid test tag');
let text=fs.readFileSync(path.join(work,'verify-installed-ui.mjs'),'utf8');
text=text.replace("path.join(stage,'installed-ui-final')",`path.join(stage,'${tag}')`);
const needle="mark('map-ready');";
if(text.split(needle).length!==2)throw Error('Test patch context changed');
text=text.replace(needle,needle+"\n await js(`(()=>{for(const b of document.querySelectorAll('button'))if(b.textContent.includes('已阅')&&b.textContent.includes('闭卷'))b.click();if(window.TM_Changelog){TM_Changelog.markRead();TM_Changelog.close();}})()`);\n await sleep(700);mark('changelog-dismissed');");
const script=path.join(work,tag+'.mjs');fs.writeFileSync(script,text);
const dir=path.join(stage,tag);fs.mkdirSync(dir,{recursive:true});
const out=fs.openSync(path.join(dir,'process.stdout.log'),'w'),err=fs.openSync(path.join(dir,'process.stderr.log'),'w');
const env={...process.env,SHAOSONG_REPO:root,SHAOSONG_STAGE:stage};delete env.ELECTRON_RUN_AS_NODE;
console.log('RUNNING_ISOLATED_ELECTRON '+tag);
const result=spawnSync(path.join(root,'node_modules/electron/dist/electron.exe'),[script],{cwd:root,env,timeout:240000,stdio:['ignore',out,err],windowsHide:true});
fs.closeSync(out);fs.closeSync(err);
const summary={status:result.status,signal:result.signal,error:result.error?.message||null};fs.writeFileSync(path.join(dir,'process-result.json'),JSON.stringify(summary,null,2));
console.log(JSON.stringify(summary));process.exitCode=result.status===0&&!result.signal&&!result.error?0:1;
