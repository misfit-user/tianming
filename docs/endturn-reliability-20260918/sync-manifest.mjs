import fs from 'node:fs';
import cp from 'node:child_process';
import crypto from 'node:crypto';
const dir = 'docs/endturn-reliability-20260918', file = 'web/startup-script-phases.json';
const baseline = JSON.parse(fs.readFileSync(dir + '/baseline.json','utf8'));
const changes = JSON.parse(fs.readFileSync(dir + '/changes.json','utf8'));
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const before = fs.readFileSync(file), record = changes.filter(row=>row.file===file).at(-1), first = baseline.files.find(row=>row.file===file);
const expected = record ? record.after : first && first.sha256;
if (expected && sha(before) !== expected) throw Error('Concurrent startup manifest edit; reconcile before regenerating');
const backup = baseline.backup + '/' + file;
if (!fs.existsSync(backup)) fs.writeFileSync(backup, before, { flag: 'wx' });
const source = sha(fs.readFileSync('web/index.html'));
cp.execFileSync(process.execPath,['web/scripts/build-startup-phase-manifest.js'],{stdio:'inherit'});
if (sha(fs.readFileSync('web/index.html')) !== source) throw Error('Index changed during regeneration');
changes.push({file,before:sha(before),after:sha(fs.readFileSync(file)),at:new Date().toISOString(),generator:'web/scripts/build-startup-phase-manifest.js',lateCaptured:!first});
fs.writeFileSync(dir + '/changes.json',JSON.stringify(changes,null,2));
const result = cp.spawnSync(process.execPath,['web/scripts/build-startup-phase-manifest.js','--check'],{encoding:'utf8'});
fs.writeFileSync(dir + '/manifest-check.json',JSON.stringify({at:new Date().toISOString(),exit:result.status,output:result.stdout+result.stderr},null,2));
console.log(result.stdout,result.stderr); if(result.status)process.exitCode=result.status;
