import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
const root=path.resolve(process.argv[2]||'.'),work=fs.realpathSync(path.join(root,'docs/shaosong-map-integration-20260917'));
const stage=path.join(work,'location-stage'),tag=process.argv[3]||'installed-location-final';
assert.ok(/^installed-location-[a-z0-9-]+$/.test(tag));
let text=fs.readFileSync(path.join(work,'verify-installed-ui.mjs'),'utf8');
text=text.replace("path.join(stage,'installed-ui-final')",`path.join(stage,'${tag}')`);
const needle="mark('map-ready');";assert.equal(text.split(needle).length,2);
text=text.replace(needle,needle+`\n await js(\`(()=>{for(const b of document.querySelectorAll('button'))if(b.textContent.includes('已阅')&&b.textContent.includes('闭卷'))b.click();if(window.TM_Changelog){TM_Changelog.markRead();TM_Changelog.close();}})()\`);
 await sleep(700);
 report.locations=await js(fs.readFileSync(path.join(stage,'verify-live-location-page.js'),'utf8'));
 check('live-location-integration',report.locations.failed===0,report.locations);
 mark('location-behaviour-verified',{passed:report.locations.passed});`);
const script=path.join(work,tag+'.mjs'),dir=path.join(stage,tag);fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(script,text);
const out=fs.openSync(path.join(dir,'stdout.log'),'w'),err=fs.openSync(path.join(dir,'stderr.log'),'w');
const env={...process.env,SHAOSONG_REPO:root,SHAOSONG_STAGE:stage};delete env.ELECTRON_RUN_AS_NODE;
console.log('RUNNING '+tag);
const result=spawnSync(path.join(root,'node_modules/electron/dist/electron.exe'),[script],{cwd:root,env,timeout:240000,stdio:['ignore',out,err],windowsHide:true});
fs.closeSync(out);fs.closeSync(err);const summary={status:result.status,signal:result.signal,error:result.error?.message||null};
fs.writeFileSync(path.join(dir,'process-result.json'),JSON.stringify(summary,null,2));console.log(JSON.stringify(summary));
process.exitCode=result.status===0&&!result.signal&&!result.error?0:1;
