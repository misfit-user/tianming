#!/usr/bin/env node
'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'tm-ai-infra.js'), 'utf8');
const block = src.slice(src.indexOf('function toChineseReignYear('), src.indexOf('function getSE('));
const ctx = { P: {}, GM: {}, _getDaysPerTurn: () => 10, Number, Math, isFinite };
vm.createContext(ctx);
vm.runInContext(block, ctx);
ctx.P.time = { year: 840, calendar: 'lunar', startMonth: 1, startDay: 14, enableEraName: true, enableGanzhiDay: false };
ctx.GM = { turn: 1, eraNames: [{ name: '开成', startYear: 836, startMonth: 1, startDay: 1 }] };
assert.strictEqual(ctx.getTSText(1), '开成五年春正月十四');
assert.strictEqual(ctx.calcDateFromTurn(1).lunarMonth, 1, '农历起点不得减一月');
assert.strictEqual(ctx.calcDateFromTurn(1).gzDayStr, '');
assert(!ctx._tmTimeDisplayParts(1).tip.includes('840年1月14日'), '没有公历对照时不展示伪公历月日');
assert(ctx._tmTimeDisplayParts(1).tip.includes('农历正月十四'));
assert.strictEqual(ctx.getTSText(3), '开成五年春二月初四');
ctx._tmSyncGMCalendar(ctx.GM, 3);
assert.deepStrictEqual([ctx.GM.year, ctx.GM.month, ctx.GM.day], [840, 2, 4]);
assert.strictEqual(ctx.getTSText(36), '开成六年春正月初四', '农历跨正月时年份必须进位');
ctx._tmSyncGMCalendar(ctx.GM, 36);
assert.deepStrictEqual([ctx.GM.year, ctx.GM.month, ctx.GM.day], [841, 1, 4]);
ctx.GM.eraNames.push({ name: '承和', startYear: 840, startMonth: 2, startDay: 1 });
assert.strictEqual(ctx.getTSText(3), '承和元年春二月初四', '玩家另定年号被正常采用');
const names = ['孟春','仲春','季春','孟夏','仲夏','季夏','孟秋','仲秋','季秋','孟冬','仲冬','季冬'];
names.forEach((name, i) => assert.strictEqual(ctx._tmSeasonFromDate({ lunarMonth: i + 1 }).name, name));
ctx.P.time.enableGanzhiDay = true;
assert(ctx.getTSText(1).endsWith('正月十四'), '农历起点没有公历对照不能猜干支日');
ctx.P.time = { year: 1627, startMonth: 9, startDay: 1, startLunarMonth: 8, startLunarDay: 1, enableGanzhiDay: false };
assert(ctx.getTSText(1).endsWith('秋八月初一'), '阳历配置也尊重显式禁用');
delete ctx.P.time.enableGanzhiDay;
assert(ctx.calcDateFromTurn(1).gzDayStr && ctx.getTSText(1).endsWith(ctx.calcDateFromTurn(1).gzDayStr + '日'), '未禁用的旧阳历配置保留干支日');
const shell = fs.readFileSync(path.join(root, 'tm-shell-extras.js'), 'utf8');
const player = fs.readFileSync(path.join(root, 'tm-player-core.js'), 'utf8');
assert(shell.includes('_tmSeasonFromDate(_dateForWeather)'), '侧栏使用同一农历季节入口');
assert(player.includes('_tmSeasonFromDate(_dateForWeather)'), '顶栏使用同一农历季节入口');
console.log('[smoke-calendar-lunar-display] PASS: 农历起点、日名、月年进位、玩家年号、十二月季节及旧配置');
