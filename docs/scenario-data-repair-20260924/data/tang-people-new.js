function stats(base, delta) {
  const out = Object.assign({}, base);
  Object.keys(delta || {}).forEach((k) => { out[k] = Math.max(0, Math.min(100, out[k] + delta[k])); });
  return out;
}

function wuchang(delta, confidence, note, sources) {
  const scores = stats(WUCHANG, delta);
  return { scores, confidence, note, sources };
}

